-- lvim-colorscheme.extra.secmon: generate a secmon-tui theme file from the lvim-colorscheme palette.
--
-- secmon-tui is a ratatui security monitor whose interface reads its palette from
-- `~/.config/secmon/themes/<name>.toml` — a flat TOML of the 9 unified roles. It is pointed at
-- from `~/.config/secmon/config.toml` with `theme = "<name>"`:
--
--     mkdir -p ~/.config/secmon/themes
--     cp extras/secmon/*.toml ~/.config/secmon/themes/
--
-- Every role is optional in secmon-tui: a missing or malformed one falls back to the built-in
-- default, so a partial file never leaves the UI unreadable. The role derivation is identical to
-- clipack's (see extra/misc/clipack.lua for the full reasoning).
--
---@module "lvim-colorscheme.extra.secmon"

local util = require("lvim-colorscheme.util")

local M = {}

--- @param colors ColorScheme
--- @param _ table  highlight groups, unused: secmon maps from the palette
--- @param opts table
function M.generate(colors, _, opts)
    local term_bg = colors.terminal.background

    local text = util.ensure_contrast(colors.terminal.foreground, term_bg, 4.5)
    local muted = util.ensure_contrast(colors.comment, term_bg, 3)
    local accent = util.ensure_contrast(colors.blue, term_bg, 3)
    local accent_alt = util.ensure_contrast(colors.orange, term_bg, 3)
    local success = util.ensure_contrast(colors.green, term_bg, 3)
    local warning = util.ensure_contrast(colors.red, term_bg, 3)
    local error_color = util.ensure_contrast(colors.red, term_bg, 3)

    local title_dark = util.ensure_contrast(colors.bg, accent, 3)
    local title_light = "#ffffff"
    local title_fg = title_light
    if util.contrast(title_dark, accent) > util.contrast(title_light, accent) then
        title_fg = title_dark
    end

    local subtle = util.ensure_contrast(colors.bg_light, term_bg, 1.6)

    colors.secmon_theme_name = "Lvim" .. (opts.style:gsub("^%l", string.upper))
    colors.secmon_text = text
    colors.secmon_muted = muted
    colors.secmon_accent = accent
    colors.secmon_accent_alt = accent_alt
    colors.secmon_success = success
    colors.secmon_warning = warning
    colors.secmon_error = error_color
    colors.secmon_title_fg = title_fg
    colors.secmon_subtle = subtle

    return util.template(
        [[# ${secmon_theme_name}
# Generated by lvim-colorscheme for secmon-tui — https://github.com/lvim-tech/secmon
#
# Install:
#   mkdir -p ~/.config/secmon/themes
#   cp extras/secmon/*.toml ~/.config/secmon/themes/
#
# Use, in ~/.config/secmon/config.toml: theme = "${secmon_theme_name}"
#
# Every role is optional; a missing one falls back to the built-in default.

accent     = "${secmon_accent}"      # selection / active highlight, title & border accent
accent_alt = "${secmon_accent_alt}"  # headings, suspects, staged edits, new peers
text       = "${secmon_text}"        # default foreground
muted      = "${secmon_muted}"       # hints and secondary labels
subtle     = "${secmon_subtle}"      # unfocused borders and dividers
success    = "${secmon_success}"     # freeze on, healthy state
warning    = "${secmon_warning}"     # a warning (same hue as error, not bold)
error      = "${secmon_error}"       # an error / destructive action (bold)
title_fg   = "${secmon_title_fg}"    # foreground drawn on the accent badge
]],
        colors
    )
end

return M
