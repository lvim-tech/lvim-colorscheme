-- lvim-colorscheme.extra.mailforge: generate a mailforge theme file from the lvim-colorscheme palette.
--
-- mailforge is a Bubble Tea mail configurator sharing keyforge's theme loader. Like the rest of the
-- family it reads a per-app palette from `~/.config/mailforge/themes/<name>.yaml`:
--
--     mkdir -p ~/.config/mailforge/themes
--     cp extras/mailforge/*.yaml ~/.config/mailforge/themes/
--
-- It uses the same ten hue roles keyforge does (its UI tells apart red/yellow/green/blue/purple/
-- orange), so its file carries those rather than clipack's nine semantic roles. The values are the
-- palette's own hues, with bg_alt and dim blended off bg and fg; mailforge lifts anything below its
-- readability floor on load.
--
---@module "lvim-colorscheme.extra.mailforge"

local util = require("lvim-colorscheme.util")

local M = {}

-- blend mixes two "#rrggbb" colours by t (linear RGB), matching the loader's own blend().
local function blend(a, b, t)
    local function rgb(h)
        h = h:gsub("#", "")
        return tonumber(h:sub(1, 2), 16), tonumber(h:sub(3, 4), 16), tonumber(h:sub(5, 6), 16)
    end
    local ar, ag, ab = rgb(a)
    local br, bg, bb = rgb(b)
    local function mix(x, y)
        return math.floor(x + (y - x) * t + 0.5)
    end
    return string.format("#%02x%02x%02x", mix(ar, br), mix(ag, bg), mix(ab, bb))
end

--- @param colors ColorScheme
--- @param _ table  highlight groups, unused: mailforge maps from the palette
--- @param opts table
function M.generate(colors, _, opts)
    colors.mailforge_theme_name = "Lvim" .. (opts.style:gsub("^%l", string.upper))
    colors.mailforge_bg = colors.bg
    colors.mailforge_bg_alt = blend(colors.bg, colors.fg, 0.06)
    colors.mailforge_fg = colors.fg
    colors.mailforge_dim = blend(colors.fg, colors.bg, 0.45)
    colors.mailforge_red = colors.red
    colors.mailforge_yellow = colors.yellow
    colors.mailforge_green = colors.green
    colors.mailforge_blue = colors.blue
    colors.mailforge_purple = colors.purple
    colors.mailforge_orange = colors.orange

    return util.template(
        [[---
# ${mailforge_theme_name}
# Generated by lvim-colorscheme for mailforge — https://github.com/lvim-tech/mailforge
#
# Install:
#   mkdir -p ~/.config/mailforge/themes
#   cp extras/mailforge/*.yaml ~/.config/mailforge/themes/
#
# Use, in mailforge's config: theme: ${mailforge_theme_name}
#
# mailforge lifts any role below its readability floor on load; a missing role
# falls back to the built-in Everforest.

name: ${mailforge_theme_name}

colors:
    # Base background and the one-step-off surface (selected rows).
    bg: "${mailforge_bg}"
    bg_alt: "${mailforge_bg_alt}"
    # Default foreground and the dimmed secondary text.
    fg: "${mailforge_fg}"
    dim: "${mailforge_dim}"
    # Semantic hues: red open-now, yellow caution, green verified, blue key,
    # purple prior/context, orange note.
    red: "${mailforge_red}"
    yellow: "${mailforge_yellow}"
    green: "${mailforge_green}"
    blue: "${mailforge_blue}"
    purple: "${mailforge_purple}"
    orange: "${mailforge_orange}"
]],
        colors
    )
end

return M
