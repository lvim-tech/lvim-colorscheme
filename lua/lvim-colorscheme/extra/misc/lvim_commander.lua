-- lvim-colorscheme.extra.lvim_commander: generate a lvim-commander theme from the lvim-colorscheme palette.
--
-- lvim-commander (github.com/lvim-tech/lvim-fuzzy-commander, the `lvc` two-panel file manager) draws the same
-- lvim look as lvim-fuzzy — it shares its renderer (lvim-fuzzy-ui) — so its theme is lvim-fuzzy's (every
-- role resolved through lvim-utils' highlight factory, see lvim_fuzzy.lua) plus the roles of a file
-- listing: directories, executables, symlinks, broken symlinks. It reads
-- `~/.config/lvim-commander/themes/<name>.toml`, picked with `theme = "<name>"` in
-- `~/.config/lvim-commander/config.toml` (and falls back to lvim-fuzzy's themes directory). By hand:
--
--     mkdir -p ~/.config/lvim-commander/themes
--     cp extras/lvim_commander/*.toml ~/.config/lvim-commander/themes/
--
---@module "lvim-colorscheme.extra.lvim_commander"

local M = {}

---@param v any
---@return string?
local function hex(v)
    if type(v) == "number" then
        return string.format("#%06x", v)
    end
    if type(v) == "string" and v:match("^#%x%x%x%x%x%x$") then
        return v:lower()
    end
    return nil
end

--- @param colors ColorScheme
--- @param groups table
--- @param opts table
function M.generate(colors, groups, opts)
    local base = require("lvim-colorscheme.extra.misc.lvim_fuzzy").generate(colors, groups, opts)
    base = base:gsub(
        "^# lvim%-fuzzy theme — generated by lvim%-colorscheme %(scripts/build lvim_fuzzy%)%. Do not edit:",
        "# lvim-commander theme — generated by lvim-colorscheme (scripts/build lvim_commander). Do not edit:"
    )
    -- the file-listing roles, from the palette accents (what `ls --color` / eza use them for)
    local function fg(name, attrs)
        local c = hex(colors[name])
        if not c then
            return nil
        end
        local parts = { 'fg = "' .. c .. '"' }
        for _, a in ipairs(attrs or {}) do
            parts[#parts + 1] = a .. " = true"
        end
        return "{ " .. table.concat(parts, ", ") .. " }"
    end
    local extra = {
        { "dir", fg("blue", { "bold" }) },
        { "exec", fg("green") },
        { "link", fg("cyan", { "italic" }) },
        { "broken", fg("red", { "italic" }) },
    }
    local out = { (base:gsub("\n$", "")) }
    for _, r in ipairs(extra) do
        if r[2] then
            out[#out + 1] = r[1] .. " = " .. r[2]
        end
    end
    return table.concat(out, "\n") .. "\n"
end

return M
