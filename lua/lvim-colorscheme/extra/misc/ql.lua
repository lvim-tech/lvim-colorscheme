-- lvim-colorscheme.extra.ql: generate a ql theme file from the lvim-colorscheme palette.
--
-- ql is a modular command launcher whose embedded Bubble Tea menu reads its palette from
-- `~/.config/ql/themes/<name>.yaml`, in the same 9-role schema clipack uses.
--
--     mkdir -p ~/.config/ql/themes
--     cp extras/ql/*.yaml ~/.config/ql/themes/
--
-- The role derivation is identical to clipack's (see extra/misc/clipack.lua).
--
---@module "lvim-colorscheme.extra.ql"

local util = require("lvim-colorscheme.util")

local M = {}

--- @param colors ColorScheme
--- @param _ table  highlight groups, unused: ql maps from the palette
--- @param opts table
function M.generate(colors, _, opts)
    local term_bg = colors.terminal.background

    local text = util.ensure_contrast(colors.terminal.foreground, term_bg, 4.5)
    local muted = util.ensure_contrast(colors.comment, term_bg, 3.2)
    local accent = util.ensure_contrast(colors.blue, term_bg, 3)
    local accent_alt = util.ensure_contrast(colors.orange, term_bg, 3)
    local success = util.ensure_contrast(colors.green, term_bg, 3)
    local warning = util.ensure_contrast(colors.red, term_bg, 3)
    local error_color = util.ensure_contrast(colors.red, term_bg, 3)

    -- The title ink: badge text on `accent`, the active tab label on `accent_alt`. The rule lives
    -- in `util.title_fg` and is judged once per theme on EVERY surface the badge-painting family
    -- paints (these floored accents and keyforge/mailforge's raw hues alike), so all seven apps
    -- put byte-identical ink on their chips.
    local title_fg = util.title_fg(colors)

    local subtle = util.ensure_contrast(colors.bg_light, term_bg, 1.6)

    colors.ql_theme_name = "Lvim" .. (opts.style:gsub("^%l", string.upper))
    colors.ql_text = text
    colors.ql_muted = muted
    colors.ql_accent = accent
    colors.ql_accent_alt = accent_alt
    colors.ql_success = success
    colors.ql_warning = warning
    colors.ql_error = error_color
    colors.ql_title_fg = title_fg
    colors.ql_subtle = subtle

    return util.template(
        [[---
# ${ql_theme_name}
# Generated by lvim-colorscheme for ql — https://github.com/lvim-tech/ql
#
# Install:
#   mkdir -p ~/.config/ql/themes
#   cp extras/ql/*.yaml ~/.config/ql/themes/
#
# Use, in ~/.config/ql/config.toml: [theme] name = "${ql_theme_name}"

name: ${ql_theme_name}

colors:
    # Selection cursor, focused list border and the title badge background.
    accent: "${ql_accent}"
    # Section headings and step markers.
    accent_alt: "${ql_accent_alt}"
    # Default foreground.
    text: "${ql_text}"
    # Descriptions, hints.
    muted: "${ql_muted}"
    # Unfocused borders.
    subtle: "${ql_subtle}"
    # Completed operations.
    success: "${ql_success}"
    # Non-fatal problems.
    warning: "${ql_warning}"
    # Failures.
    error: "${ql_error}"
    # Text of the title badge, drawn on `accent`.
    title_fg: "${ql_title_fg}"
]],
        colors
    )
end

return M
