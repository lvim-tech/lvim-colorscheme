-- lvim-colorscheme.extra.themer: generate a themer theme file from the lvim-colorscheme palette.
--
-- themer is the theme switcher; its OWN Bubble Tea interface reads its palette from
-- `~/.config/themer/themes/<name>.yaml`, in the same 9-role schema clipack uses.
--
--     mkdir -p ~/.config/themer/themes
--     cp extras/themer/*.yaml ~/.config/themer/themes/
--
-- The role derivation is identical to clipack's (see extra/misc/clipack.lua).
--
---@module "lvim-colorscheme.extra.themer"

local util = require("lvim-colorscheme.util")

local M = {}

--- @param colors ColorScheme
--- @param _ table  highlight groups, unused: themer maps from the palette
--- @param opts table
function M.generate(colors, _, opts)
    local term_bg = colors.terminal.background

    local text = util.ensure_contrast(colors.terminal.foreground, term_bg, 4.5)
    local muted = util.ensure_contrast(colors.comment, term_bg, 3.2)
    local accent = util.ensure_contrast(colors.blue, term_bg, 3)
    local accent_alt = util.ensure_contrast(colors.orange, term_bg, 3)
    local success = util.ensure_contrast(colors.green, term_bg, 3)
    local warning = util.ensure_contrast(colors.red, term_bg, 3)
    local error_color = util.ensure_contrast(colors.red, term_bg, 3)

    -- The title ink: badge text on `accent`, the active tab label on `accent_alt`. The rule lives
    -- in `util.title_fg` and is judged once per theme on EVERY surface the badge-painting family
    -- paints (these floored accents and keyforge/mailforge's raw hues alike), so all seven apps
    -- put byte-identical ink on their chips.
    local title_fg = util.title_fg(colors)

    local subtle = util.ensure_contrast(colors.bg_light, term_bg, 1.6)

    colors.themer_theme_name = "Lvim" .. (opts.style:gsub("^%l", string.upper))
    colors.themer_text = text
    colors.themer_muted = muted
    colors.themer_accent = accent
    colors.themer_accent_alt = accent_alt
    colors.themer_success = success
    colors.themer_warning = warning
    colors.themer_error = error_color
    colors.themer_title_fg = title_fg
    colors.themer_subtle = subtle

    return util.template(
        [[---
# ${themer_theme_name}
# Generated by lvim-colorscheme for themer — https://github.com/lvim-tech/themer
#
# Install:
#   mkdir -p ~/.config/themer/themes
#   cp extras/themer/*.yaml ~/.config/themer/themes/
#
# Use, in themer's config: theme.name: ${themer_theme_name}

name: ${themer_theme_name}

colors:
    # Selection cursor, focused pane border and the title badge background.
    accent: "${themer_accent}"
    # Section headings, the active tab and step markers.
    accent_alt: "${themer_accent_alt}"
    # Default foreground.
    text: "${themer_text}"
    # Descriptions, field labels, hints.
    muted: "${themer_muted}"
    # Unfocused pane borders.
    subtle: "${themer_subtle}"
    # Completed operations.
    success: "${themer_success}"
    # Non-fatal problems.
    warning: "${themer_warning}"
    # Failures.
    error: "${themer_error}"
    # Text of the title badge, drawn on `accent`.
    title_fg: "${themer_title_fg}"
]],
        colors
    )
end

return M
