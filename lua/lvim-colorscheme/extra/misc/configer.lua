-- lvim-colorscheme.extra.configer: generate a configer theme file from the lvim-colorscheme palette.
--
-- configer is a config manager whose Bubble Tea interface reads its palette from
-- `~/.config/configer/themes/<name>.yaml`, in the same 9-role schema clipack uses. The file is a
-- COMPLETE theme, so dropping it in is all that is needed:
--
--     mkdir -p ~/.config/configer/themes
--     cp extras/configer/*.yaml ~/.config/configer/themes/
--
-- and then, in configer's config, select the theme by name (e.g. LvimNord_dark).
--
-- The role derivation is identical to clipack's (see extra/misc/clipack.lua for the full
-- reasoning): blue/orange/green/red accents lifted to a contrast floor against the terminal
-- background, text/muted/subtle derived, title_fg the better-contrasting end on the accent.
--
---@module "lvim-colorscheme.extra.configer"

local util = require("lvim-colorscheme.util")

local M = {}

--- @param colors ColorScheme
--- @param _ table  highlight groups, unused: configer maps from the palette
--- @param opts table
function M.generate(colors, _, opts)
    local term_bg = colors.terminal.background

    local text = util.ensure_contrast(colors.terminal.foreground, term_bg, 4.5)
    local muted = util.ensure_contrast(colors.comment, term_bg, 3.2)
    local accent = util.ensure_contrast(colors.blue, term_bg, 3)
    local accent_alt = util.ensure_contrast(colors.orange, term_bg, 3)
    local success = util.ensure_contrast(colors.green, term_bg, 3)
    local warning = util.ensure_contrast(colors.red, term_bg, 3)
    local error_color = util.ensure_contrast(colors.red, term_bg, 3)

    -- The title ink: badge text on `accent`, the active tab label on `accent_alt`. The rule lives
    -- in `util.title_fg` and is judged once per theme on EVERY surface the badge-painting family
    -- paints (these floored accents and keyforge/mailforge's raw hues alike), so all seven apps
    -- put byte-identical ink on their chips.
    local title_fg = util.title_fg(colors)

    local subtle = util.ensure_contrast(colors.bg_light, term_bg, 1.6)

    colors.configer_theme_name = "Lvim" .. (opts.style:gsub("^%l", string.upper))
    colors.configer_text = text
    colors.configer_muted = muted
    colors.configer_accent = accent
    colors.configer_accent_alt = accent_alt
    colors.configer_success = success
    colors.configer_warning = warning
    colors.configer_error = error_color
    colors.configer_title_fg = title_fg
    colors.configer_subtle = subtle

    return util.template(
        [[---
# ${configer_theme_name}
# Generated by lvim-colorscheme for configer — https://github.com/lvim-tech/configer
#
# Install:
#   mkdir -p ~/.config/configer/themes
#   cp extras/configer/*.yaml ~/.config/configer/themes/
#
# Use, in configer's config: theme.name: ${configer_theme_name}
#
# Anything here can be overridden per-machine; only the keys you repeat are replaced.

name: ${configer_theme_name}

colors:
    # Selection cursor, focused pane border and the title badge background.
    accent: "${configer_accent}"
    # Section headings, the active tab and step markers.
    accent_alt: "${configer_accent_alt}"
    # Default foreground.
    text: "${configer_text}"
    # Descriptions, field labels, hints.
    muted: "${configer_muted}"
    # Unfocused pane borders.
    subtle: "${configer_subtle}"
    # Completed operations.
    success: "${configer_success}"
    # Non-fatal problems.
    warning: "${configer_warning}"
    # Failures.
    error: "${configer_error}"
    # Text of the title badge, drawn on `accent`.
    title_fg: "${configer_title_fg}"
]],
        colors
    )
end

return M
