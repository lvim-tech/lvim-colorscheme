-- lvim-colorscheme.extra.lvim_fuzzy: generate a lvim-fuzzy theme from the lvim-colorscheme palette.
--
-- lvim-fuzzy (github.com/lvim-tech/lvim-fuzzy-cli) is the terminal fuzzy finder that draws
-- lvim-picker's look WITHOUT Neovim. It reads a theme from
-- `~/.config/lvim-fuzzy/themes/<name>.toml` (`--theme <name>` or `theme = "<name>"` in its config):
--
--     mkdir -p ~/.config/lvim-fuzzy/themes
--     cp extras/lvim_fuzzy/*.toml ~/.config/lvim-fuzzy/themes/
--
-- Every role is resolved HERE through lvim-utils' own highlight factory
-- (`lvim-utils.config.highlight`) — the same code that colours lvim-picker inside Neovim — so the
-- finder is byte-identical to the picker, and a tint change in lvim-utils' `config/ui.lua` reaches
-- the finder on the next `scripts/build lvim_fuzzy`. `[palette]` carries the raw accents (file
-- icons and syntax use them).
--
---@module "lvim-colorscheme.extra.lvim_fuzzy"

local M = {}

-- role in the theme file → the highlight group that styles it in lvim-picker / lvim-ui
-- stylua: ignore
local ROLES = {
    { "panel",          "LvimUiPeekNormal" },
    { "row_odd",        "LvimUiMsgAreaRowOdd" },
    { "row_even",       "LvimUiMsgAreaRowEven" },
    { "sel_odd",        "LvimUiMsgAreaSelOdd" },
    { "sel_even",       "LvimUiMsgAreaSelEven" },
    { "match",          "LvimUiMsgAreaMatch" },
    { "marker",         "LvimUiPickerMarker" },
    { "prompt",         "LvimUiPickerPrompt" },
    { "input",          "LvimUiPickerInput" },
    { "caret",          "LvimUiPickerCursor" },
    { "title",          "LvimUiPeekTitle" },
    { "counter",        "LvimUiPeekCounter" },
    { "count",          "LvimUiPeekCount" },
    { "border",         "LvimUiPeekBorder" },
    { "file_bar",       "LvimUiPeekFileBar" },
    { "file_name",      "LvimUiPeekFile" },
    { "file_icon",      "LvimUiPeekFileIcon" },
    { "file_dir",       "LvimUiPickerPreviewDir" },
    { "footer",         "LvimUiFooter" },
    { "footer_key",     "LvimUiFooterKey" },
    { "footer_label",   "LvimUiFooterLabel" },
    { "footer_sep",     "LvimUiFooterSep" },
    { "chevron",        "LvimUiFooterChevron" },
    { "help_key_odd",   "LvimUiHelpKeyOdd" },
    { "help_desc_odd",  "LvimUiHelpDescOdd" },
    { "help_key_even",  "LvimUiHelpKeyEven" },
    { "help_desc_even", "LvimUiHelpDescEven" },
    { "popup",          "LvimUiNormal" },
    { "popup_border",   "LvimUiBorder" },
    { "notify",         "LvimNotifyNormal" },
    { "preview_match",  "LvimUiMsgAreaMatch" },
    { "preview_focus",  "LvimUiPeekTitle" },
}

-- editor groups (from the colorscheme itself) used by the built-in file preview
local EDITOR = {
    { "line_nr", "LineNr" },
    { "cursor_line", "CursorLine" },
    { "normal", "Normal" },
}

local PALETTE = {
    "bg",
    "bg_dark",
    "bg_light",
    "fg",
    "comment",
    "blue",
    "yellow",
    "red",
    "green",
    "orange",
    "cyan",
    "teal",
    "magenta",
    "purple",
}

---@param v any
---@return string?
local function hex(v)
    if type(v) == "number" then
        return string.format("#%06x", v)
    end
    if type(v) == "string" and v:match("^#%x%x%x%x%x%x$") then
        return v:lower()
    end
    return nil
end

--- One role as an inline TOML table.
---@param hl table?
---@return string
local function role(hl)
    hl = hl or {}
    local parts = {}
    local fg, bg = hex(hl.fg), hex(hl.bg)
    if fg then
        parts[#parts + 1] = 'fg = "' .. fg .. '"'
    end
    if bg then
        parts[#parts + 1] = 'bg = "' .. bg .. '"'
    end
    for _, a in ipairs({ "bold", "italic", "underline", "reverse" }) do
        if hl[a] then
            parts[#parts + 1] = a .. " = true"
        end
    end
    return "{ " .. table.concat(parts, ", ") .. " }"
end

--- @param colors ColorScheme
--- @param groups table  the colorscheme's own highlight groups (LineNr, CursorLine, Normal)
--- @param opts table
function M.generate(colors, groups, opts)
    local ui = require("lvim-utils.config.highlight")(colors)
    local name = "Lvim" .. (opts.style:gsub("^%l", string.upper):gsub("_(%l)", string.upper))
    local out = {
        "# lvim-fuzzy theme — generated by lvim-colorscheme (scripts/build lvim_fuzzy). Do not edit:",
        "# the roles come from lvim-utils' highlight factory, exactly as lvim-picker draws them.",
        'name = "' .. name .. '"',
        "",
        "[palette]",
    }
    for _, k in ipairs(PALETTE) do
        local v = hex(colors[k])
        if v then
            out[#out + 1] = k .. ' = "' .. v .. '"'
        end
    end
    out[#out + 1] = ""
    out[#out + 1] = "[roles]"
    for _, r in ipairs(ROLES) do
        out[#out + 1] = r[1] .. " = " .. role(ui[r[2]])
    end
    for _, r in ipairs(EDITOR) do
        out[#out + 1] = r[1] .. " = " .. role(groups and groups[r[2]])
    end
    return table.concat(out, "\n") .. "\n"
end

return M
